  <AbsoluteFill
    style={{
      background: `radial-gradient(circle at 30% 40%, ${C.bg2} 0%, ${C.bg1} 70%)`,
      fontFamily,
      color: C.text,
    }}
  >
    {children}
  </AbsoluteFill>
